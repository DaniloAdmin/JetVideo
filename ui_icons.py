def icon(master, name, color, size=18):
    scale = 4
    stroke = 7
    art = Image.new('RGBA', (24 * scale, 24 * scale))
    painter = ImageDraw.Draw(art)

    def point(x, y):
        return round(x * scale), round(y * scale)

    def dot(x, y, radius):
        painter.ellipse((*point(x - radius, y - radius), *point(x + radius, y + radius)), fill=color)

    for path in _PATHS.get(name, ()):
        painter.line([point(x, y) for x, y in path], fill=color, width=stroke, joint='curve')
        dot(*path[0], .75)
        dot(*path[-1], .75)
    for x0, y0, x1, y1 in _RINGS.get(name, ()):
        painter.ellipse((*point(x0, y0), *point(x1, y1)), outline=color, width=stroke)
    for x, y in _DOTS.get(name, ()):
        dot(x, y, 1.05)
    return ImageTk.PhotoImage(art.resize((size, size), Image.Resampling.LANCZOS), master=master)
